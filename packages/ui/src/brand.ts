/**
 * App identity (docs/design/DESIGN_SYSTEM.md, "Ícones e identidade dos apps"). One mark, two surfaces:
 * - Portal: the institutional blue mark on white; browser theme in brand.primary.
 * - PDV: the same mark in operation.primary on the PDV's dark operational surface.
 * Status colors are never used as identity: operation.primary shares its hex with status.success, and only the token is
 * referenced here, never redefined.
 */
export const appBrand = {
  portal: { name: "Germinatura", shortName: "Germinatura", background: "#FFFFFF", mark: "#0E208E", theme: "#001EC5" },
  pdv: { name: "PDV Germinatura", shortName: "PDV", background: "#070B18", mark: "#00B982", theme: "#070B18" },
} as const;
export type BrandApp = keyof typeof appBrand;

/**
 * rounded: browser/PWA "any" icon (the surface has its own rounded corners).
 * maskable: full-bleed surface, mark inside the 80% safe circle, so Android may crop it to any shape.
 * full: full-bleed square for Apple touch icons and favicons (the platform rounds it).
 */
export type AppIconShape = "rounded" | "maskable" | "full";

// Bounding box of the mark inside its 200 × 200 design box.
const MARK_BOX = { x: 50, y: 24, width: 120, height: 139 } as const;
// Height of the mark as a share of the icon; the maskable one keeps the whole mark within the 40% safe radius.
const MARK_HEIGHT: Record<AppIconShape, number> = { rounded: 0.66, maskable: 0.56, full: 0.66 };

/** The app icon as SVG: the official geometry, centered and scaled, on the app's surface. */
export function appIconSvg(app: BrandApp, shape: AppIconShape) {
  const { background, mark } = appBrand[app];
  const scale = (200 * MARK_HEIGHT[shape]) / MARK_BOX.height;
  const centerX = MARK_BOX.x + MARK_BOX.width / 2;
  const centerY = MARK_BOX.y + MARK_BOX.height / 2;
  const surface = shape === "rounded"
    ? `<rect width="200" height="200" rx="40" fill="${background}"/>`
    : `<rect width="200" height="200" fill="${background}"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200">${surface}`
    + `<g fill="${mark}" transform="translate(100 100) scale(${scale.toFixed(4)}) translate(${-centerX} ${-centerY})">${brandShapes()}</g></svg>`;
}

